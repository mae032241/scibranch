"""Actual pre-migration contracts remain readable without executing new hooks."""
import json
from pathlib import Path

import pytest

from scidiscovery.builtin_plugin import CORE_PLUGIN
from scidiscovery.general_science_plugin import PLUGIN as GENERAL_PLUGIN
from curve_score.plugin import PLUGIN as CURVE_PLUGIN
from tcad_artifact.plugin import PLUGIN as TCAD_PLUGIN
from scidiscovery.operations.catalog import compile_catalog
from scidiscovery.operations.spec import canonical_digest
from scidiscovery.operations.workspace import WorkspaceProtocolError


GOLDEN = json.loads((Path(__file__).parents[1] / 'fixtures/finalizer_contracts_4aa72027.json').read_bytes())
PLUGINS = (CORE_PLUGIN, GENERAL_PLUGIN, CURVE_PLUGIN, TCAD_PLUGIN)


def test_exact_pre_migration_specs_are_readable_but_finalizers_are_not_executable():
    # Captured in a separate process importing the actual archived commit,
    # including its then-current and three supported historical generations.
    # The fixed original digests cannot be regenerated by the reconstruction.
    catalog = compile_catalog(PLUGINS)
    for original in GOLDEN['contracts']:
        operation_id, version, digest = (original[key] for key in ('operation_id', 'version', 'digest'))
        current = catalog.operation(operation_id)
        assert current.digest != digest
        restored = catalog.recorded_operation(operation_id, version=version, digest=digest)
        assert restored.digest == digest
        assert canonical_digest(restored.spec) == original['operation_spec_sha256']
        assert catalog.recorded_contract_status(operation_id, version=version, digest=digest) == 'supported_historical'
        for key, contract in original['finalizers'].items():
            assert restored.component_specs[key].model_dump(mode='json') == contract['spec']
            finalizer = restored.implementations[key]
            assert finalizer.projection_version == contract['projection_version']
            assert finalizer is not current.implementations[key]
            with pytest.raises(WorkspaceProtocolError, match='read-only'):
                finalizer(None)
            with pytest.raises(WorkspaceProtocolError, match='read-only'):
                finalizer.draft_schema({}, 'fixture')
        assert not catalog.can_recover(operation_id, digest, current.digest)
        assert not catalog.can_recover(operation_id, current.digest, digest)
        with pytest.raises(KeyError):
            catalog.recorded_operation(operation_id, version='unknown-version', digest=digest)
        with pytest.raises(KeyError):
            catalog.recorded_operation(operation_id, version=version, digest='f' * 64)


def test_changed_installed_contracts_do_not_inherit_fixed_original_identities():
    # A predecessor declares only its prior path/projection. It cannot erase
    # changes to the actual installed Spec to manufacture an original digest.
    changed = tuple(plugin.model_copy(update={'components': tuple(
        spec.model_copy(update={'configuration_identity': 'different-scientific-contract'})
        if spec.kind == 'workspace_finalizer' else spec for spec in plugin.components)})
        for plugin in PLUGINS)
    catalog = compile_catalog(changed)
    for original in GOLDEN['contracts']:
        operation_id, version, digest = (original[key] for key in ('operation_id', 'version', 'digest'))
        assert catalog.recorded_contract_status(operation_id, version=version, digest=digest) == 'unavailable'
        with pytest.raises(KeyError):
            catalog.recorded_operation(operation_id, version=version, digest=digest)
        assert not catalog.can_recover(operation_id, digest, catalog.operation(operation_id).digest)
